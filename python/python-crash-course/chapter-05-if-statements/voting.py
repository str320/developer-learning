# Simple if Statements

age = 19

if age >= 18:
    print(f"Your age is {age}, old enough to vote!")
    print("Have you registered to vote yet?")

# if-else Statements   

age = 17

if age >= 18:
    print(f"\nYou age is {age}, old enough to vote!")
    print("Have you registered to vote yet?")
else:
    print(f"\nSorry your age is {age}, you are too young to vote.")
    print("Please register to vote as soon as you turn 18!")


