# Strings are text. You can use either single or double quotes to create a string in Python.
# In this example, we use double quotes to create a string that contains a person's name. The title() method is used to capitalize the first letter of each word in the string. 
name = "ada lovelace"

# The title() method returns a new string with the first letter of each word capitalized. The original string remains unchanged.
print(name.title())
# The upper() method returns a new string with all characters in uppercase. The original string remains unchanged.
print(name.upper())
# The lower() method returns a new string with all characters in lowercase. The original string remains unchanged.
print(name.lower())


